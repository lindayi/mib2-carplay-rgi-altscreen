#!/usr/bin/env python3
"""Bake Card CJK SC from pinned Noto Sans CJK SC; no runtime font dependency.

Install card-font-requirements.txt, then supply the font and Sans/LICENSE from
notofonts/noto-cjk revision f8d157532fbfaeda587e826d4cd5b21a49186f7c.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("font")
parser.add_argument("license")
args = parser.parse_args()
font_path = Path(args.font)
sha = hashlib.sha256(font_path.read_bytes()).hexdigest()
if sha != "2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b":
    parser.error("font does not match the pinned Noto Sans CJK SC Regular")
source = TTFont(font_path)
cmap = source.getBestCmap()
points = sorted(cp for cp in cmap if 0x2E80 <= cp < 0xA000 or
                0xF900 <= cp < 0xFB00 or 0xFF00 <= cp < 0xFFF0 or cp == 0x25A1)
assert all(cp in points for cp in map(ord, "\u4e2d\u6587\u7b80\u7e41\u25a1"))
font = ImageFont.truetype(str(font_path), 16)
glyphs, offsets, packed = [], [], bytearray()
for index, cp in enumerate(points):
    char = chr(cp)
    left, top, right, bottom = font.getbbox(char, anchor="ls")
    w, h = right-left, bottom-top
    image = Image.new("L", (w, h))
    ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
    values = [(value+8)//17 for value in image.tobytes()]
    offsets.append(len(packed))
    for i in range(0, len(values), 2):
        packed.append((values[i] << 4) | (values[i+1] if i+1 < len(values) else 0))
    glyphs.append((cp, index, 65535, w, h, left, top+15, round(font.getlength(char)*64)))
out = Path(__file__).resolve().parents[1] / "map_cards"
with (out / "cjk_font_data.h").open("w", encoding="ascii", newline="\n") as f:
    f.write("/* Generated by tools/generate_card_font.py; Card CJK SC, see LICENSE.OFL. */\n")
    f.write(f"/* Source SHA256: {sha}. Packed coverage is read-only; no atlas allocation. */\n")
    f.write("#define CARDS_CJK_ROW 65535\nstatic const route_glyph_t cards_cjk_glyphs[] = {\n")
    for g in glyphs:
        f.write("    {" + ",".join(map(str, g)) + "},\n")
    f.write("};\nstatic const unsigned int cards_cjk_offsets[] = {\n")
    for i in range(0, len(offsets), 16):
        f.write("    " + ",".join(map(str, offsets[i:i+16])) + ",\n")
    f.write("};\nstatic const unsigned char cards_cjk_coverage[] = {\n")
    for i in range(0, len(packed), 32):
        f.write("    " + ",".join(map(str, packed[i:i+32])) + ",\n")
    f.write("};\n")
notice = source["name"].getDebugName(0)
assert notice
license_text = Path(args.license).read_text(encoding="utf-8")
assert "SIL OPEN FONT LICENSE Version 1.1" in license_text
with (out / "LICENSE.OFL").open("w", encoding="utf-8", newline="\n") as f:
    f.write("Card CJK SC bitmap font, derived from Noto Sans CJK SC Regular.\n" +
            notice + "\n\n" + license_text)
print(f"{len(glyphs)} glyphs; {len(packed)} packed bytes; "
      f"{len(packed)+len(glyphs)*22} read-only bytes; no extra heap atlas")
